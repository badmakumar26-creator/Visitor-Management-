import 'package:intl/intl.dart';

/// The three states of the visit workflow: Registered -> Checked In -> Checked Out.
enum VisitorStatus {
  registered('Registered'),
  checkedIn('Checked In'),
  checkedOut('Checked Out');

  const VisitorStatus(this.label);
  final String label;

  static VisitorStatus fromString(String? value) {
    return VisitorStatus.values.firstWhere(
          (s) => s.label.toLowerCase() == (value ?? '').trim().toLowerCase(),
      orElse: () => VisitorStatus.registered,
    );
  }
}

/// Visitor data model. fromJson/toJson convert between API JSON (snake_case keys)
/// and Dart objects; the model is immutable, so changes go through copyWith().
class Visitor {
  final String id; // generated by the server; also the content of the QR code
  final String name;
  final String mobile;
  final String? email;
  final String visitorType;
  final String project;
  final String purpose;
  final VisitorStatus status;
  final DateTime createdAt;
  final DateTime? checkInTime;
  final DateTime? checkOutTime;

  const Visitor({
    required this.id,
    required this.name,
    required this.mobile,
    this.email,
    required this.visitorType,
    required this.project,
    required this.purpose,
    required this.status,
    required this.createdAt,
    this.checkInTime,
    this.checkOutTime,
  });

  // Workflow rule: Registered -> Checked In -> Checked Out. The UI uses these to
  // decide which button to show.
  bool get canCheckIn => status == VisitorStatus.registered;
  bool get canCheckOut => status == VisitorStatus.checkedIn;

  /// Deserialization: JSON map from the API -> Visitor. Missing fields get safe
  /// defaults; a missing id throws so bad responses are caught by the API service.
  factory Visitor.fromJson(Map<String, dynamic> json) {
    final id = json['id']?.toString();
    if (id == null || id.isEmpty) {
      throw const FormatException('Visitor is missing an id');
    }
    final email = json['email']?.toString().trim();
    return Visitor(
      id: id,
      name: (json['name'] ?? '').toString(),
      mobile: (json['mobile'] ?? '').toString(),
      email: (email == null || email.isEmpty) ? null : email,
      visitorType: (json['visitor_type'] ?? 'Other').toString(),
      project: (json['project'] ?? '').toString(),
      purpose: (json['purpose'] ?? '').toString(),
      status: VisitorStatus.fromString(json['status']?.toString()),
      createdAt: _parse(json['created_at']) ?? DateTime.now(),
      checkInTime: _parse(json['check_in_time']),
      checkOutTime: _parse(json['check_out_time']),
    );
  }

  /// Serialization: Visitor -> JSON body for POST/PUT.
  /// - id is omitted when empty so the server generates it.
  /// - email is sent as "" when empty (some mock APIs reject null for String fields).
  /// - check-in/out times are omitted until they exist.
  Map<String, dynamic> toJson() => {
    if (id.isNotEmpty) 'id': id,
    'name': name,
    'mobile': mobile,
    'email': email ?? '',
    'visitor_type': visitorType,
    'project': project,
    'purpose': purpose,
    'status': status.label,
    'created_at': formatIso(createdAt),
    if (checkInTime != null) 'check_in_time': formatIso(checkInTime!),
    if (checkOutTime != null) 'check_out_time': formatIso(checkOutTime!),
  };

  Visitor copyWith({
    String? name,
    String? mobile,
    String? email,
    bool clearEmail = false,
    String? visitorType,
    String? project,
    String? purpose,
    VisitorStatus? status,
    DateTime? checkInTime,
    DateTime? checkOutTime,
  }) {
    return Visitor(
      id: id,
      name: name ?? this.name,
      mobile: mobile ?? this.mobile,
      email: clearEmail ? null : (email ?? this.email),
      visitorType: visitorType ?? this.visitorType,
      project: project ?? this.project,
      purpose: purpose ?? this.purpose,
      status: status ?? this.status,
      createdAt: createdAt,
      checkInTime: checkInTime ?? this.checkInTime,
      checkOutTime: checkOutTime ?? this.checkOutTime,
    );
  }

  static DateTime? _parse(dynamic value) {
    if (value == null) return null;
    final text = value.toString();
    if (text.isEmpty) return null;
    return DateTime.tryParse(text)?.toLocal();
  }

  /// ISO-8601 with the device UTC offset, e.g. 2026-10-26T10:30:00+05:30.
  static String formatIso(DateTime dt) {
    final local = dt.toLocal();
    final offset = local.timeZoneOffset;
    final sign = offset.isNegative ? '-' : '+';
    final abs = offset.abs();
    final hh = abs.inHours.toString().padLeft(2, '0');
    final mm = (abs.inMinutes % 60).toString().padLeft(2, '0');
    final base = DateFormat("yyyy-MM-dd'T'HH:mm:ss").format(local);
    return '$base$sign$hh:$mm';
  }
}